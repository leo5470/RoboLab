#!/usr/bin/env python3
"""Generate Simple-PnP v2 task drafts from generation records (plan step 5).

    .venv/bin/python tools/simple_pnp_v2/generate_tasks.py \
        --record-dir output/simple_pnp_v2_validation/generation

Writes one task per *authored* slot to robolab/tasks/single_pnp_v2_drafts/
(outside automatic discovery; load by explicit name) and a drafts manifest.

    .venv/bin/python tools/simple_pnp_v2/generate_tasks.py \
        --record-dir output/simple_pnp_v2_validation/generation \
        --qualified output/simple_pnp_v2_validation/production/gate_status.json

With --qualified (the per-slot gate record from gate_status.py) it writes the
promoted tasks to robolab/tasks/single_pnp_v2/ instead, and refuses unless every
authored slot passed every gate for its exact scene hash. Promoted tasks are
still outside DEFAULT_TASK_SUBFOLDERS: load them by name (--task-dirs single_pnp_v2).
Success and full credit use object_resting_in_container with one explicit
parameter dictionary, including the two values v1 inherited from code
defaults. Instructions follow v1 wording. They do not mention a handle:
the plan allows that only after the visibility gate passes.
Move a task to robolab/tasks/single_pnp_v2/ only after its gates pass.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import py_compile
import re

ROOT = Path(__file__).resolve().parents[2]
DRAFT_DIR = ROOT / "robolab/tasks/single_pnp_v2_drafts"
QUALIFIED_DIR = ROOT / "robolab/tasks/single_pnp_v2"
EPISODE_LENGTH_S = 50
PLACEMENT_PARAMS = {
    "gripper_name": "gripper",
    "exclude_contact_with": "table",
    "settle_time_s": 0.5,
    "linear_threshold": 0.05,
    "angular_threshold": 0.5,
    "position_tolerance": 0.001,
    "rotation_tolerance_deg": 0.5,
    "support_force_threshold": 0.01,
    "max_container_tilt_deg": 15.0,
    # PhysX reports 0.2-0.7 rad/s for resting multi-collider bodies; compare
    # speeds from consecutive observed poses, as v2 scene preparation does.
    "speed_source": "pose",
}


def class_name(stem):
    return "SimplePnpV2" + "".join(p.capitalize() for p in stem.removeprefix("pnp_").split("_")) + "Task"


def task_source(record, status="DRAFT: required gates pending."):
    scene = Path(record["scene"])
    stem = scene.stem
    task = class_name(stem)
    term = task.removesuffix("Task") + "Terminations"
    target = record["prim_name"]
    params = "\n".join(f"    {json.dumps(k)}: {json.dumps(v)}," for k, v in PLACEMENT_PARAMS.items())
    return f'''# Auto-generated by tools/simple_pnp_v2/generate_tasks.py. {status}
# Scene: {record["scene"]} (sha256 {record["measurements"]["scene_sha256"]})
# Generation record: {record["slot"]}

from dataclasses import dataclass

import isaaclab.envs.mdp as mdp
from isaaclab.managers import TerminationTermCfg as DoneTerm
from isaaclab.utils import configclass

from robolab.core.scenes.utils import import_scene
from robolab.core.task.conditionals import object_resting_in_container, pick_and_place
from robolab.core.task.task import Task

PLACEMENT_PARAMS = {{
{params}
}}


@configclass
class {term}:
    time_out = DoneTerm(func=mdp.time_out, time_out=True)
    success = DoneTerm(
        func=object_resting_in_container,
        params={{"object": {target!r}, "container": "grey_bin", **PLACEMENT_PARAMS}},
    )


@dataclass
class {task}(Task):
    contact_object_list = [{target!r}, "grey_bin", "table"]
    scene = import_scene("simple_pnp_v2/{scene.name}", contact_object_list)
    terminations = {term}
    instruction = {{
        "default": "Pick up the {target} and place it in the grey bin.",
        "vague": "Put the item in the bin.",
        "specific": "Grasp the {target} from the tabletop and release it inside the grey bin.",
    }}
    episode_length_s: int = {EPISODE_LENGTH_S}
    attributes = ["semantics"]
    subtasks = [
        pick_and_place(
            object=[{target!r}],
            container="grey_bin",
            logical="all",
            score=1.0,
            placement_func=object_resting_in_container,
            placement_params=PLACEMENT_PARAMS,
        )
    ]
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--record-dir", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, help="default: drafts dir, or the qualified dir with --qualified")
    parser.add_argument("--qualified", type=Path, help="gate_status.json; write promoted (qualified) tasks")
    args = parser.parse_args()
    gates = json.loads(args.qualified.read_text())["slots"] if args.qualified else None
    args.out_dir = args.out_dir or (QUALIFIED_DIR if gates is not None else DRAFT_DIR)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    rows, names = [], set()
    for path in sorted(args.record_dir.glob("pnp_*.json")):
        record = json.loads(path.read_text())
        if record["status"] != "authored":
            continue
        scene = ROOT / record["scene"]
        if hashlib.sha256(scene.read_bytes()).hexdigest() != record["measurements"]["scene_sha256"]:
            raise SystemExit(f"{scene} changed since its generation record")
        if not re.fullmatch(r"pnp_\d{3}_\w+_\d{2}", scene.stem):
            raise SystemExit(f"Unexpected scene name {scene.name}")
        task = class_name(scene.stem)
        if task in names:
            raise SystemExit(f"Duplicate class {task}")
        names.add(task)
        status = "DRAFT: required gates pending."
        if gates is not None:
            g = gates.get(record["slot"])
            if g is None or g["scene_sha256"] != record["measurements"]["scene_sha256"] \
                    or any(v not in ("passed", "not_applicable") for v in g["gates"].values()):
                raise SystemExit(f"{record['slot']}: not qualified ({g and g['gates']})")
            status = ("QUALIFIED: geometry, physics, Franka reach" + (", visibility" if g["gates"]["visibility"] == "passed" else "")
                      + f" passed. Evidence: {args.qualified.as_posix()}")
        out = args.out_dir / f"{scene.stem}_task.py"
        out.write_text(task_source(record, status))
        py_compile.compile(str(out), doraise=True)
        rows.append({"task": out.name, "class_name": task, "scene": f"simple_pnp_v2/{scene.name}",
                     "scene_sha256": record["measurements"]["scene_sha256"], "target": record["prim_name"],
                     "destination": "grey_bin", "catalog_index": record["catalog_index"], "layout": record["layout"],
                     "episode_length_s": EPISODE_LENGTH_S,
                     "gates": gates[record["slot"]]["gates"] if gates is not None else record["gates"],
                     "task_checks": gates[record["slot"]]["task_checks"] if gates is not None else
                     {"syntax": "passed", "runtime_import": "pending", "goal_semantics": "pending"}})
    status = ("qualified: every task's scene passed all gates; not in DEFAULT_TASK_SUBFOLDERS (load by name)"
              if gates is not None else "draft: required gates pending; not registered")
    manifest = {"format_version": 1, "status": status,
                "gate_evidence": args.qualified.as_posix() if gates is not None else None,
                "success_condition": "object_resting_in_container", "placement_params": PLACEMENT_PARAMS,
                "tasks": rows}
    (args.out_dir / "manifest.json").write_text(json.dumps(manifest, indent=1))
    init = args.out_dir / "__init__.py"
    if not init.exists():
        init.write_text("")
    print(f"wrote {len(rows)} {'qualified tasks' if gates is not None else 'task drafts'} to {args.out_dir}")


if __name__ == "__main__":
    main()
