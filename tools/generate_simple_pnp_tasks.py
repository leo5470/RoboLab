#!/usr/bin/env python3
"""Generate one RoboLab task definition for every simple-PnP scene."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SCENE_DIR = ROOT / "assets/scenes/simple_pnp"
SCENE_MANIFEST = SCENE_DIR / "manifest.json"
OUT_DIR = ROOT / "robolab/tasks/single_pnp"
EPISODE_LENGTH_S = 50


def class_name(scene_stem: str) -> str:
    return "Simple" + "".join(part.capitalize() for part in scene_stem.split("_")) + "Task"


def task_source(scene_name: str, target_name: str) -> str:
    scene_stem = Path(scene_name).stem
    task_class = class_name(scene_stem)
    termination_class = task_class.removesuffix("Task") + "Terminations"
    default = f"Pick up the {target_name} and place it in the grey bin."
    vague = "Put the item in the bin."
    specific = f"Grasp the {target_name} from the tabletop and release it inside the grey bin."
    return f'''# Auto-generated by tools/generate_simple_pnp_tasks.py.
# Scene: assets/scenes/simple_pnp/{scene_name}

from dataclasses import dataclass

import isaaclab.envs.mdp as mdp
from isaaclab.managers import TerminationTermCfg as DoneTerm
from isaaclab.utils import configclass

from robolab.core.scenes.utils import import_scene
from robolab.core.task.conditionals import object_in_container, pick_and_place
from robolab.core.task.task import Task


@configclass
class {termination_class}:
    time_out = DoneTerm(func=mdp.time_out, time_out=True)
    success = DoneTerm(
        func=object_in_container,
        params={{
            "object": {target_name!r},
            "container": "grey_bin",
            "gripper_name": "gripper",
            "tolerance": 0.01,
            "require_contact_with": True,
            "require_gripper_detached": True,
        }},
    )


@dataclass
class {task_class}(Task):
    contact_object_list = [{target_name!r}, "grey_bin", "table"]
    scene = import_scene("simple_pnp/{scene_name}", contact_object_list)
    terminations = {termination_class}
    instruction = {{
        "default": {default!r},
        "vague": {vague!r},
        "specific": {specific!r},
    }}
    episode_length_s: int = {EPISODE_LENGTH_S}
    attributes = ["semantics"]
    subtasks = [
        pick_and_place(
            object=[{target_name!r}],
            container="grey_bin",
            logical="all",
            score=1.0,
        )
    ]
'''


def main() -> None:
    manifest = json.loads(SCENE_MANIFEST.read_text())
    scenes = manifest["scenes"]
    if OUT_DIR.exists() and any(OUT_DIR.iterdir()):
        raise FileExistsError(f"refusing to overwrite non-empty task directory: {OUT_DIR}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    records = []
    for scene in scenes:
        scene_name = scene["scene"]
        target_name = scene["target"]["name"]
        scene_path = SCENE_DIR / scene_name
        if not scene_path.is_file():
            raise FileNotFoundError(scene_path)
        task_name = f"{Path(scene_name).stem}_task.py"
        task_class = class_name(Path(scene_name).stem)
        (OUT_DIR / task_name).write_text(task_source(scene_name, target_name))
        records.append(
            {
                "task": task_name,
                "class_name": task_class,
                "scene": f"simple_pnp/{scene_name}",
                "target": target_name,
                "destination": "grey_bin",
                "episode_length_s": EPISODE_LENGTH_S,
            }
        )

    (OUT_DIR / "__init__.py").write_text('"""Generated simple pick-and-place tasks."""\n')
    (OUT_DIR / "manifest.json").write_text(
        json.dumps(
            {
                "description": "One 50-second grasp-and-place task per simple-PnP scene",
                "scene_manifest": "assets/scenes/simple_pnp/manifest.json",
                "task_count": len(records),
                "episode_length_s": EPISODE_LENGTH_S,
                "success_condition": "object_in_container with gripper detachment",
                "tasks": records,
            },
            indent=2,
        )
        + "\n"
    )
    print(f"Generated {len(records)} task files in {OUT_DIR}")


if __name__ == "__main__":
    main()
