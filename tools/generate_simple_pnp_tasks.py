#!/usr/bin/env python3
"""Generate one RoboLab task definition for every simple-PnP scene."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SCENE_DIR = ROOT / "assets/scenes/simple_pnp"
SCENE_MANIFEST = SCENE_DIR / "manifest.json"
OUT_DIR = ROOT / "robolab/tasks/single_pnp"
EPISODE_LENGTH_S = 50
RESTING_PARAMS = {
    "exclude_contact_with": "table",
    "settle_time_s": 0.5,
    "linear_threshold": 0.05,
    "angular_threshold": 0.5,
    "position_tolerance": 0.001,
    "rotation_tolerance_deg": 0.5,
}
SUCCESS_CONDITION = "object_resting_in_container: released, bin-supported and pose-stable for 0.5 seconds"


def class_name(scene_stem: str) -> str:
    return "Simple" + "".join(part.capitalize() for part in scene_stem.split("_")) + "Task"


def task_source(scene_name: str, target_name: str, *, resting: bool = True) -> str:
    scene_stem = Path(scene_name).stem
    task_class = class_name(scene_stem)
    termination_class = task_class.removesuffix("Task") + "Terminations"
    default = f"Pick up the {target_name} and place it in the grey bin."
    vague = "Put the item in the bin."
    specific = f"Grasp the {target_name} from the tabletop and release it inside the grey bin."
    conditional = "object_resting_in_container" if resting else "object_in_container"
    placement_lines = "\n".join(f'            "{key}": {json.dumps(value)},' for key, value in RESTING_PARAMS.items())
    success_params = placement_lines if resting else '''            "tolerance": 0.01,
            "require_contact_with": True,
            "require_gripper_detached": True,'''
    subtask_params = f'''
            placement_func=object_resting_in_container,
            placement_params={{
{placement_lines.replace('            ', '                ')}
            }},''' if resting else ""
    return f'''# Auto-generated by tools/generate_simple_pnp_tasks.py.
# Scene: assets/scenes/simple_pnp/{scene_name}

from dataclasses import dataclass

import isaaclab.envs.mdp as mdp
from isaaclab.managers import TerminationTermCfg as DoneTerm
from isaaclab.utils import configclass

from robolab.core.scenes.utils import import_scene
from robolab.core.task.conditionals import {conditional}, pick_and_place
from robolab.core.task.task import Task


@configclass
class {termination_class}:
    time_out = DoneTerm(func=mdp.time_out, time_out=True)
    success = DoneTerm(
        func={conditional},
        params={{
            "object": {target_name!r},
            "container": "grey_bin",
            "gripper_name": "gripper",
{success_params}
        }},
    )


@dataclass
class {task_class}(Task):
    contact_object_list = [{target_name!r}, "grey_bin", "table"]
    scene = import_scene("simple_pnp/{scene_name}", contact_object_list)
    terminations = {termination_class}
    instruction = {{
        "default": {default!r},
        "vague": {vague!r},
        "specific": {specific!r},
    }}
    episode_length_s: int = {EPISODE_LENGTH_S}
    attributes = ["semantics"]
    subtasks = [
        pick_and_place(
            object=[{target_name!r}],
            container="grey_bin",
            logical="all",
            score=1.0,{subtask_params}
        )
    ]
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--update-existing", action="store_true",
                        help="Migrate the existing generated task set, preserving filtering metadata; "
                             "refuse task files with custom edits")
    args = parser.parse_args()
    manifest = json.loads(SCENE_MANIFEST.read_text())
    scenes = manifest["scenes"]
    task_manifest = {}
    if args.update_existing:
        task_manifest = json.loads((OUT_DIR / "manifest.json").read_text())
        existing = task_manifest["tasks"]
        expected = {f"{Path(scene['scene']).stem}_task.py" for scene in scenes}
        if ({record["task"] for record in existing} != expected
                or {path.name for path in OUT_DIR.glob("*_task.py")} != expected):
            raise ValueError("Task files and scene/task manifests must describe the same retained set")
        # Preflight the whole migration before changing any file. Preserve custom
        # edits rather than silently regenerating them from the scene manifest.
        for scene in scenes:
            scene_name, target = scene["scene"], scene["target"]["name"]
            path = OUT_DIR / f"{Path(scene_name).stem}_task.py"
            if path.read_text() not in (task_source(scene_name, target, resting=False), task_source(scene_name, target)):
                raise ValueError(f"Task has custom edits; refusing to overwrite: {path}")
    elif OUT_DIR.exists() and any(OUT_DIR.iterdir()):
        raise FileExistsError(f"refusing to overwrite non-empty task directory: {OUT_DIR}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    records = []
    for scene in scenes:
        scene_name = scene["scene"]
        target_name = scene["target"]["name"]
        scene_path = SCENE_DIR / scene_name
        if not scene_path.is_file():
            raise FileNotFoundError(scene_path)
        task_name = f"{Path(scene_name).stem}_task.py"
        task_class = class_name(Path(scene_name).stem)
        source = task_source(scene_name, target_name)
        path = OUT_DIR / task_name
        if not path.exists() or path.read_text() != source:
            path.write_text(source)
        records.append(
            {
                "task": task_name,
                "class_name": task_class,
                "scene": f"simple_pnp/{scene_name}",
                "target": target_name,
                "destination": "grey_bin",
                "episode_length_s": EPISODE_LENGTH_S,
            }
        )

    if not args.update_existing:
        (OUT_DIR / "__init__.py").write_text('"""Generated simple pick-and-place tasks."""\n')
    task_manifest.update(
        description="One 50-second grasp-and-place task per simple-PnP scene",
        scene_manifest="assets/scenes/simple_pnp/manifest.json",
        task_count=len(records),
        episode_length_s=EPISODE_LENGTH_S,
        success_condition=SUCCESS_CONDITION,
        success_params=RESTING_PARAMS,
        tasks=records,
    )
    (OUT_DIR / "manifest.json").write_text(
        json.dumps(
            task_manifest,
            indent=2,
        )
        + "\n"
    )
    print(f"Generated {len(records)} task files in {OUT_DIR}")


if __name__ == "__main__":
    main()
